import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile } from 'node:fs/promises';
import { api, login } from './http.mjs';

test('restored tenant retains settled bill snapshots, split payments and sales exactly', async () => {
  assert.ok(process.env.VERIFY_RECOVERY_RECORD, 'recovery case requires a completed runner-owned restore drill');
  const expected = JSON.parse(await readFile(process.env.VERIFY_RECOVERY_RECORD, 'utf8'));
  const { accessToken } = await login();
  const order = await api(`/orders/${expected.orderId}`, undefined, accessToken);
  assert.equal(order.status, 200); assert.equal(order.data.status, 'PAID');
  assert.equal(order.data.bill.totalPaise, 15698); assert.deepEqual(order.data.bill, expected.bill);
  const check = await api(`/checks/${expected.checkId}`, undefined, accessToken);
  assert.equal(check.status, 200); assert.equal(check.data.status, 'CLOSED');
  assert.equal(check.data.totalPaise, 15698); assert.equal(check.data.duePaise, 0);
  assert.deepEqual(check.data.payments.map(value => value.amountPaise), [7000, 8698]);
  const report = await api('/reports/today', undefined, accessToken);
  assert.deepEqual(report.data, expected.report);
  assert.deepEqual(order.data.inventory, expected.inventory.snapshot);
  const ingredients = await api('/inventory', undefined, accessToken);
  const ingredient = ingredients.data.ingredients.find(value => value.id === expected.inventory.ingredientId);
  assert.deepEqual(ingredient, expected.inventory.ingredient); assert.equal(ingredient.balanceMilli, -50000);
  const history = await api(`/inventory/movements?ingredientId=${ingredient.id}`, undefined, accessToken);
  assert.deepEqual(history.data, expected.inventory.history);
  assert.equal(history.data.movements.filter(value => value.kind === 'CONSUMPTION').length, 2);
  const recipe = await api(`/inventory/recipes?itemId=${expected.inventory.itemId}&kind=BASE&version=1`, undefined, accessToken);
  assert.deepEqual(recipe.data, expected.inventory.recipe); assert.equal(recipe.data.components[0].quantityMilli, 75000);
  const count = await api(`/inventory/counts/${expected.count.document.id}`, undefined, accessToken);
  assert.equal(count.status, 200); assert.deepEqual(count.data, expected.count.document);
  const replay = await api('/inventory/counts', expected.count.command, accessToken);
  assert.equal(replay.status, 200); assert.deepEqual(replay.data, expected.count.document);
  const counted = (await api('/inventory', undefined, accessToken)).data.ingredients.find(value => value.id === expected.count.ingredient.id);
  assert.deepEqual(counted, expected.count.ingredient); assert.equal(counted.balanceMilli, 12000);
  const countHistory = await api(`/inventory/movements?ingredientId=${counted.id}`, undefined, accessToken);
  assert.deepEqual(countHistory.data, expected.count.history); assert.equal(countHistory.data.movements.length, 1);
  assert.equal(countHistory.data.movements[0].stockCountId, count.data.id);
});
